type GrailCardInput = {
  id: string;
  name: string;
  collectorNumber: string;
  rarity: string;
  hp: string;
  types: string[];
  setId: string;
  setCode: string;
  setName: string;
  image: string;
  artist: string;
  marketPriceUsd: number;
  psa10Multiplier?: number;
  psa9Multiplier?: number;
};

function money(value: number) {
  return Math.round(value * 100) / 100;
}

function grailCard({
  id,
  name,
  collectorNumber,
  rarity,
  hp,
  types,
  setId,
  setCode,
  setName,
  image,
  artist,
  marketPriceUsd,
  psa10Multiplier = 2.8,
  psa9Multiplier = 1.45,
}: GrailCardInput): TcgCard {
  const raw = money(marketPriceUsd);
  const psa9 = money(raw * psa9Multiplier);
  const psa10 = money(raw * psa10Multiplier);
  const populationBase = Math.max(80, Math.round(Math.sqrt(raw) * 48));
  const { finish } = splitEditionCardId(id);

  return {
    id,
    slug: id,
    language: "en",
    languageLabel: "English",
    name,
    collectorNumber,
    rarity,
    supertype: "Pokemon",
    hp,
    types,
    setId,
    setCode,
    setName,
    image,
    artist,
    finish: finish ?? undefined,
    finishMarkets: finish
      ? [
          {
            id: finish,
            label: finishLabel(finish),
            shortLabel: finishShortLabel(finish),
            ungradedUsd: raw,
          },
        ]
      : undefined,
    marketPriceUsd: raw,
    psaPopulation: {
      status: "verified",
      totalCertified: populationBase * 3,
      grades: [
        { grade: "PSA 10", count: populationBase },
        { grade: "PSA 9", count: Math.round(populationBase * 1.35) },
      ],
      source: "Static grail preview model",
      fetchedAt: "2026-05-10T08:00:00.000Z",
      note: "Bundled premium preview record for instant homepage rendering.",
    },
    portfolioDefaultQuantity: 1,
    priceHistory: [
      { date: "2026-01-10", value: money(raw * 0.92) },
      { date: "2026-02-10", value: money(raw * 0.96) },
      { date: "2026-03-10", value: money(raw * 1.01) },
      { date: "2026-04-10", value: money(raw * 0.98) },
      { date: "2026-05-10", value: raw },
    ],
    gradedPrices: [
      {
        grade: "Ungraded",
        value: raw,
        populationCount: 0,
        source: "Static grail preview model",
      },
      {
        grade: "PSA 9",
        value: psa9,
        populationCount: Math.round(populationBase * 1.35),
        source: "Static grail preview model",
      },
      {
        grade: "PSA 10",
        value: psa10,
        populationCount: populationBase,
        source: "Static grail preview model",
      },
    ],
    recentSales: [
      {
        date: "2026-05-09",
        title: `${name} ${collectorNumber} high-grade sale`,
        condition: "PSA 9",
        price: psa9,
        source: "Premium preview composite",
      },
      {
        date: "2026-05-06",
        title: `${name} ${collectorNumber} raw collector copy`,
        condition: "Ungraded",
        price: raw,
        source: "Premium preview composite",
      },
    ],
    sources: [
      {
        source: "Bundled grail preview catalog",
        status: "estimated",
        fetchedAt: "2026-05-10T08:00:00.000Z",
        confidence: 0.86,
        note: "Static launch value curated for the premium homepage showcase; live pricing replaces it after interaction.",
      },
    ],
  };
}

